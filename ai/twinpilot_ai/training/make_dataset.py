"""Generate the fixed evaluation dataset (normal + injected faults + unseen conditions).

Runs are generated by the scripted operator with fixed seeds, so the dataset is fully
reproducible from the manifest. Data files are not committed; the manifest is.

uv run python -m twinpilot_ai.training.make_dataset --version v1 --workers 6
"""

from __future__ import annotations

import argparse
import hashlib
import shutil
import subprocess
from concurrent.futures import ProcessPoolExecutor
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import yaml

from twinpilot_sim import __version__ as sim_version
from twinpilot_sim.operator import OperatorConfig
from twinpilot_sim.params import default_params
from twinpilot_sim.recorder import PARQUET, TELEMETRY, file_sha256, to_parquet
from twinpilot_sim.runner import run_scenario
from twinpilot_sim.schema import FaultSpec, FaultType

DURATION = 120.0
SEVERITIES = (0.3, 0.6, 0.9)
JOINT_TARGETS = ("swing_joint", "boom_joint", "arm_joint", "bucket_joint")
NOISE_TARGETS = (
    "arm_joint.effort",
    "boom_joint.velocity",
    "imu.roll",
    "chassis.vibration_rms",
    "bucket_joint.position",
)
STUCK_TARGETS = (
    "swing_joint.position",
    "boom_joint.position",
    "imu.pitch",
    "bucket_joint.velocity",
)


@dataclass
class RunSpec:
    run_id: str
    split: str
    seed: int
    faults: list[FaultSpec] = field(default_factory=list)
    speed_scale: float = 1.0
    payload_scale: float = 1.0
    condition: str = "nominal"
    duration: float = DURATION


def _fault(rng: np.random.Generator, ftype: FaultType, severity: float, idx: int) -> FaultSpec:
    if ftype in (FaultType.JOINT_LAG, FaultType.FRICTION_INCREASE):
        target = str(rng.choice(JOINT_TARGETS))
    elif ftype is FaultType.SENSOR_NOISE:
        target = str(rng.choice(NOISE_TARGETS))
    elif ftype is FaultType.SENSOR_STUCK:
        target = str(rng.choice(STUCK_TARGETS))
    else:
        target = "hydraulic"
    return FaultSpec(
        fault_id=f"fault-{idx:04d}",
        type=ftype,
        target=target,
        start_time=round(float(rng.uniform(20, 70)), 2),
        duration=round(float(rng.uniform(15, 30)), 2),
        severity=severity,
    )


def plan(n_normal: int = 40, seeds_per_cell: int = 4) -> list[RunSpec]:
    """Deterministic run plan. Splits are by run (never by window) to avoid leakage."""
    specs: list[RunSpec] = []
    rng = np.random.Generator(np.random.PCG64(20261011))
    n_train = round(n_normal * 0.6)
    n_val = round(n_normal * 0.2)
    for i in range(n_normal):
        split = "train" if i < n_train else "val" if i < n_train + n_val else "test"
        specs.append(
            RunSpec(
                f"normal-{i:03d}",
                split,
                seed=100 + i,
                speed_scale=round(float(rng.uniform(0.8, 1.2)), 3),
            )
        )
    idx = 0
    for ftype in FaultType:
        for sev in SEVERITIES:
            for k in range(seeds_per_cell):
                idx += 1
                specs.append(
                    RunSpec(
                        f"fault-{ftype.value.lower()}-s{int(sev * 10)}-{k}",
                        "val" if k == 0 else "test",
                        seed=1000 + idx,
                        faults=[_fault(rng, ftype, sev, idx)],
                        speed_scale=round(float(rng.uniform(0.8, 1.2)), 3),
                    )
                )
    # unseen conditions: never used for training or threshold calibration
    conditions = [
        ("heavy-payload", 1.0, 1.5),
        ("slow-operator", 0.6, 1.0),
        ("fast-operator", 1.4, 1.0),
    ]
    u = 0
    for name, speed, payload in conditions:
        for k in range(2):
            u += 1
            specs.append(
                RunSpec(f"unseen-{name}-normal-{k}", "unseen", 5000 + u, [], speed, payload, name)
            )
        for ftype in (
            FaultType.JOINT_LAG,
            FaultType.FRICTION_INCREASE,
            FaultType.TEMP_RISE,
            FaultType.SENSOR_STUCK,
            FaultType.SENSOR_NOISE,
        ):
            u += 1
            idx += 1
            specs.append(
                RunSpec(
                    f"unseen-{name}-{ftype.value.lower()}",
                    "unseen",
                    5000 + u,
                    [_fault(rng, ftype, float(rng.choice(SEVERITIES)), idx)],
                    speed,
                    payload,
                    name,
                )
            )
    for k in range(5):  # two simultaneous faults
        u += 1
        types = rng.choice(list(FaultType), size=2, replace=False)
        faults = []
        for ft in types:
            idx += 1
            faults.append(_fault(rng, FaultType(ft), 0.6, idx))
        specs.append(
            RunSpec(f"unseen-compound-{k}", "unseen", 5000 + u, faults, 1.0, 1.0, "compound")
        )
    return specs


def _generate(args: tuple[RunSpec, str, bool]) -> dict:
    spec, out_dir, keep_jsonl = args
    res = run_scenario(
        run_id=spec.run_id,
        seed=spec.seed,
        duration=spec.duration,
        out_dir=out_dir,
        faults=spec.faults,
        scenario=spec.condition if not spec.faults else "fault",
        operator=OperatorConfig(speed_scale=spec.speed_scale, loop=True),
        payload_scale=spec.payload_scale,
        parquet=True,
    )
    if not keep_jsonl:
        (res.run_dir / TELEMETRY).unlink()
    return {
        "run_id": spec.run_id,
        "split": spec.split,
        "seed": spec.seed,
        "condition": spec.condition,
        "speed_scale": spec.speed_scale,
        "payload_scale": spec.payload_scale,
        "faults": [f.model_dump(mode="json") for f in spec.faults],
        "records": res.records,
        "parquet_sha256": file_sha256(res.run_dir / PARQUET),
        "delivered": res.metrics["delivered"],
    }


def code_version() -> str:
    try:
        return subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True
        ).stdout.strip()
    except Exception:  # noqa: BLE001
        return "unknown"


def make_dataset(
    version: str = "v1",
    root: Path | str = "datasets",
    workers: int = 4,
    specs: list[RunSpec] | None = None,
    keep_jsonl: bool = False,
    manifest_dir: Path | str | None = None,
) -> Path:
    root = Path(root)
    runs_dir = root / version / "runs"
    if runs_dir.exists():
        shutil.rmtree(runs_dir)
    runs_dir.mkdir(parents=True)
    specs = specs if specs is not None else plan()
    jobs = [(s, str(runs_dir), keep_jsonl) for s in specs]
    if workers > 1:
        with ProcessPoolExecutor(max_workers=workers) as ex:
            rows = list(ex.map(_generate, jobs))
    else:
        rows = [_generate(j) for j in jobs]
    splits: dict[str, list[str]] = {}
    for r in rows:
        splits.setdefault(r["split"], []).append(r["run_id"])
    manifest = {
        "dataset_version": version,
        "level": "L1-simulation",
        "generator": "twinpilot_ai.training.make_dataset",
        "code_version": code_version(),
        "sim_version": sim_version,
        "params_hash": default_params().params_hash(),
        "duration_s": DURATION,
        "split_policy": "by run; train = normal only; val/test/unseen disjoint",
        "counts": {k: len(v) for k, v in sorted(splits.items())},
        "plan_hash": hashlib.sha256(
            yaml.safe_dump([(s.run_id, s.seed) for s in specs]).encode()
        ).hexdigest()[:16],
        "runs": rows,
    }
    mdir = Path(manifest_dir) if manifest_dir else root / "manifests"
    mdir.mkdir(parents=True, exist_ok=True)
    path = mdir / f"{version}.yaml"
    path.write_text(yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True), encoding="utf-8")
    return path


def load_manifest(path: Path | str) -> dict:
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f)


def run_dir_for(manifest_path: Path | str, run_id: str, root: Path | str | None = None) -> Path:
    m = load_manifest(manifest_path)
    base = Path(root) if root else Path(manifest_path).parent.parent
    return base / m["dataset_version"] / "runs" / run_id


def ensure_parquet(run_dir: Path) -> Path:
    p = run_dir / PARQUET
    return p if p.exists() else to_parquet(run_dir)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", default="v1")
    ap.add_argument("--root", default="datasets")
    ap.add_argument("--workers", type=int, default=4)
    a = ap.parse_args()
    path = make_dataset(a.version, a.root, a.workers)
    m = load_manifest(path)
    print(f"manifest: {path}")
    print(f"counts  : {m['counts']}")


if __name__ == "__main__":
    main()
